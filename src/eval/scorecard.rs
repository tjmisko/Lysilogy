use super::{
    Baselines, MetricResult,
    registry::{Definition, Direction, Kind, definitions},
};
use std::{collections::BTreeMap, fmt::Write as _};

fn group_passes(group: &str, metrics: &BTreeMap<String, MetricResult>) -> bool {
    definitions()
        .into_iter()
        .filter(|d| d.id.split('.').next() == Some(group))
        .all(|d| {
            metrics
                .get(d.id)
                .and_then(|m| m.value)
                .is_some_and(|value| d.at_target(value))
        })
}

pub(super) fn acceptance_failures(metrics: &BTreeMap<String, MetricResult>) -> Vec<String> {
    let mut failures = (1..=5)
        .filter_map(|number| {
            let id = format!("G{number}");
            (!group_passes(&id, metrics)).then(|| format!("{id} is failed or unavailable"))
        })
        .collect::<Vec<_>>();
    let count = (1..=30)
        .filter(|n| group_passes(&format!("O{n}"), metrics))
        .count();
    if count < 24 {
        failures.push(format!(
            "only {count}/30 objectives at target; system acceptance requires 24"
        ));
    }
    failures
}

fn status(
    definition: Definition,
    metric: Option<&MetricResult>,
    baseline: Option<f64>,
) -> &'static str {
    let Some(value) = metric.and_then(|m| m.value) else {
        return "unavailable";
    };
    if definition.kind == Kind::Gate {
        return if definition.at_target(value) {
            "pass"
        } else {
            "FAIL"
        };
    }
    if definition.kind == Kind::Reported {
        return "reported";
    }
    if baseline.is_some_and(|baseline| definition.regresses(value, baseline)) {
        "REGRESSION"
    } else if definition.at_target(value) {
        "at target"
    } else {
        "below target"
    }
}

fn number(value: Option<f64>) -> String {
    value.map_or_else(
        || "—".into(),
        |n| {
            format!("{n:.6}")
                .trim_end_matches('0')
                .trim_end_matches('.')
                .to_owned()
        },
    )
}
fn escape(value: &str) -> String {
    value.replace('|', "\\|").replace(['\n', '\r'], " ")
}

pub(super) fn render(metrics: &BTreeMap<String, MetricResult>, baselines: &Baselines) -> String {
    let gates = (1..=5)
        .filter(|n| group_passes(&format!("G{n}"), metrics))
        .count();
    let objectives = (1..=30)
        .filter(|n| group_passes(&format!("O{n}"), metrics))
        .count();
    let mut output = format!(
        "# Knowledge base scorecard\n\nGenerated by `lysilogy eval`. Latest local results; unavailable is not a pass.\n\nHard gates: **{gates}/5 pass**. Objectives: **{objectives}/30 at target** (all components required).\nSystem acceptance requires 5/5 gates and at least 24/30 objectives; use `eval all --check --require-complete`.\n\n| ID | Metric | Suite | Current | Baseline | Target | Unit | Status |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n"
    );
    for definition in definitions() {
        let metric = metrics.get(definition.id);
        let baseline = baselines.metrics.get(definition.id).copied();
        let target = definition.target.map_or_else(
            || "reported".into(),
            |target| {
                format!(
                    "{} {}",
                    if definition.direction == Direction::Higher {
                        "≥"
                    } else {
                        "≤"
                    },
                    number(Some(target))
                )
            },
        );
        writeln!(
            output,
            "| {} | {} | {} | {} | {} | {} | {} | {} |",
            definition.id,
            definition.name,
            definition.suite,
            number(metric.and_then(|m| m.value)),
            number(baseline),
            target,
            definition.unit,
            status(definition, metric, baseline)
        )
        .expect("writing to a string cannot fail");
    }
    output.push_str("\n## Evidence and availability\n\nMeasurements are calculated from `eval/inputs/<suite>/<collector>.json` or the legacy suite file with content-verified implementation, truth-set, and observation files. G5 executes isolated tests. Results retain truth versions, source hashes, commit, case counts, cost, wall time, and the pre-run baseline. Missing cost is unknown.\n\n");
    for definition in definitions() {
        if let Some(metric) = metrics.get(definition.id) {
            if let Some(reason) = &metric.reason {
                writeln!(output, "- **{}:** {}", definition.id, escape(reason))
                    .expect("string write");
            } else if !metric.truth_sets.is_empty() {
                let versions = metric
                    .truth_sets
                    .iter()
                    .map(|(id, file)| {
                        format!(
                            "{} {} (`{}`)",
                            escape(id),
                            escape(&file.version),
                            file.sha256
                        )
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                writeln!(
                    output,
                    "- **{}:** {} cases; {}",
                    definition.id, metric.cases, versions
                )
                .expect("string write");
            }
        }
    }
    output.push_str("\n## Ratchet policy\n\nHard targets never change. Proportions permit one percentage point of objective regression; latency permits 10% relative. Other objective units permit no regression without evidence. Baselines improve automatically only when the run has no failed gate or unjustified regression. Smaller within-tolerance scores do not lower baselines. Explicit objective resets require `--justification` with a reason and a content-verified evidence file; the adjustment remains in baseline history. Reported R metrics have no target or ratchet.\n");
    output
}
